import { LocalStorageManager } from '../storage/LocalStorageManager';
import { RepositoryClient } from '../api/RepositoryClient';
import { LocalDocument } from '../models/LocalDocument';
import { SyncStatus } from '../models/SyncStatus';

/**
 * Synchronization engine for Start List documents.
 * Handles downloading and keeping the local Start List updated.
 */
export class StartListSyncEngine {
  private readonly storage: LocalStorageManager;
  private readonly apiClient: RepositoryClient;
  private readonly regattaId: string;
  private readonly regattaStartDate: string;

  constructor(
    storage: LocalStorageManager,
    apiClient: RepositoryClient,
    regattaId: string,
    regattaStartDate: string
  ) {
    this.storage = storage;
    this.apiClient = apiClient;
    this.regattaId = regattaId;
    this.regattaStartDate = regattaStartDate;
  }

  /**
   * Synchronize Start List from server.
   * Downloads the latest version and updates local storage.
   */
  async synchronize(): Promise<boolean> {
    console.log(`Starting Start List synchronization for regatta: ${this.regattaId}`);

    try {
      // Check if server is reachable
      const isOnline = await this.apiClient.isServerReachable();
      if (!isOnline) {
        console.warn('Server not reachable, working offline');
        return false;
      }

      // Get Start List from server for this regatta edition
      const serverDoc = await this.apiClient.getStartList(this.regattaId, this.regattaStartDate);

      if (!serverDoc) {
        console.warn(`No Start List found on server for regatta: ${this.regattaId}`);
        return false;
      }

      // Check if we have a local copy
      const localDoc = this.findLocalStartList();

      if (localDoc) {
        return this.updateExistingStartList(localDoc, serverDoc);
      } else {
        return this.createLocalStartList(serverDoc);
      }
    } catch (error) {
      console.error('Failed to synchronize Start List', error);
      return false;
    }
  }

  /**
   * Force refresh of Start List from server.
   * Called when notification indicates Start List has changed.
   */
  async forceRefresh(): Promise<boolean> {
    console.log(`Force refreshing Start List for regatta: ${this.regattaId}`);
    return this.synchronize();
  }

  /**
   * Get the local Start List.
   */
  getLocalStartList(): LocalDocument | null {
    return this.findLocalStartList();
  }

  /**
   * Check if local Start List needs synchronization.
   */
  needsSync(): boolean {
    const localDoc = this.findLocalStartList();

    if (!localDoc) {
      return true; // No local copy, need to download
    }

    // Check if sync failed before
    return localDoc.syncStatus === SyncStatus.FAILED;
  }

  /**
   * Get time since last sync in minutes.
   */
  getMinutesSinceLastSync(): number | null {
    const localDoc = this.findLocalStartList();

    if (!localDoc || !localDoc.lastSyncedAt) {
      return null;
    }

    const lastSync = new Date(localDoc.lastSyncedAt);
    const now = new Date();
    return Math.floor((now.getTime() - lastSync.getTime()) / (1000 * 60));
  }

  /**
   * Find local Start List document.
   */
  private findLocalStartList(): LocalDocument | null {
    const docs = this.storage.findByRegattaAndType(this.regattaId, 'START_LIST');
    return docs.length > 0 ? docs[0] : null;
  }

  /**
   * Create a new local Start List from server data.
   */
  private createLocalStartList(serverDoc: any): boolean {
    try {
      const localDoc: LocalDocument = {
        localId: '', // Will be generated by storage
        serverId: serverDoc.documentId,
        regattaId: serverDoc.regattaId,
        regattaStartDate: serverDoc.regattaStartDate,
        documentType: 'START_LIST',
        author: serverDoc.author,
        description: serverDoc.description,
        createdAt: new Date().toISOString(),
        modifiedAt: new Date().toISOString(),
        localVersion: 1,
        serverVersion: serverDoc.latestVersion,
        syncStatus: SyncStatus.SYNCED,
        lastSyncedAt: new Date().toISOString(),
        retryCount: 0,
        modelData: serverDoc.modelData,
        serializationFormat: serverDoc.serializationFormat || 'XMI',
      };

      this.storage.save(localDoc);
      console.log(
        `Created local Start List (server_id: ${serverDoc.documentId}, version: ${serverDoc.latestVersion})`
      );

      return true;
    } catch (error) {
      console.error('Failed to create local Start List', error);
      return false;
    }
  }

  /**
   * Update existing local Start List with server data.
   */
  private updateExistingStartList(localDoc: LocalDocument, serverDoc: any): boolean {
    try {
      // Check if server version is newer
      if (serverDoc.latestVersion === localDoc.serverVersion) {
        console.debug(`Local Start List is up to date (version: ${serverDoc.latestVersion})`);
        return true;
      }

      if (serverDoc.latestVersion < (localDoc.serverVersion || 0)) {
        console.warn(
          `Server version (${serverDoc.latestVersion}) is older than local version (${localDoc.serverVersion}), skipping update`
        );
        return false;
      }

      // Update local document with server data
      localDoc.modelData = serverDoc.modelData;
      localDoc.serverVersion = serverDoc.latestVersion;
      localDoc.localVersion += 1;
      localDoc.modifiedAt = new Date().toISOString();
      localDoc.syncStatus = SyncStatus.SYNCED;
      localDoc.lastSyncedAt = new Date().toISOString();
      localDoc.lastSyncError = undefined;

      this.storage.save(localDoc);

      console.log(`Updated local Start List to version ${serverDoc.latestVersion}`);
      return true;
    } catch (error) {
      console.error('Failed to update local Start List', error);

      // Mark as failed but keep old data
      localDoc.syncStatus = SyncStatus.FAILED;
      localDoc.lastSyncError = error instanceof Error ? error.message : 'Unknown error';
      localDoc.retryCount += 1;
      this.storage.save(localDoc);

      return false;
    }
  }
}
