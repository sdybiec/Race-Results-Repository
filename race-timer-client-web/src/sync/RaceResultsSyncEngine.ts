import { LocalStorageManager } from '../storage/LocalStorageManager';
import { RepositoryClient } from '../api/RepositoryClient';
import { LocalDocument } from '../models/LocalDocument';
import { SyncStatus } from '../models/SyncStatus';
import { SyncResult, DocumentRequest } from '../models/ApiTypes';

/**
 * Synchronization engine for Race Results documents.
 * Handles uploading locally captured results to the repository.
 */
export class RaceResultsSyncEngine {
  private readonly storage: LocalStorageManager;
  private readonly apiClient: RepositoryClient;
  private readonly regattaId: string;
  private readonly timerId: string;

  constructor(
    storage: LocalStorageManager,
    apiClient: RepositoryClient,
    regattaId: string,
    timerId: string
  ) {
    this.storage = storage;
    this.apiClient = apiClient;
    this.regattaId = regattaId;
    this.timerId = timerId;
  }

  /**
   * Synchronize all pending Race Results to server.
   * Uploads documents with PENDING or FAILED sync status.
   */
  async synchronizePending(): Promise<SyncResult> {
    console.log(`Starting Race Results synchronization for timer: ${this.timerId}`);

    const result: SyncResult = {
      totalDocuments: 0,
      syncedDocuments: 0,
      failedDocuments: 0,
      offline: false,
    };

    try {
      // Check if server is reachable
      const isOnline = await this.apiClient.isServerReachable();
      if (!isOnline) {
        console.warn('Server not reachable, working offline');
        result.offline = true;
        return result;
      }

      // Get all documents needing sync
      const pendingDocs = this.storage.findPendingSync();

      // Filter to only our Race Results
      const ourResults = pendingDocs.filter(
        (doc) =>
          doc.documentType === 'RACE_RESULTS' &&
          doc.timerId === this.timerId
      );

      console.log(`Found ${ourResults.length} Race Results documents to sync`);
      result.totalDocuments = ourResults.length;

      for (const localDoc of ourResults) {
        try {
          const success = await this.syncDocument(localDoc);
          if (success) {
            result.syncedDocuments++;
          } else {
            result.failedDocuments++;
          }
        } catch (error) {
          console.error(`Failed to sync document ${localDoc.localId}`, error);
          this.markSyncFailed(localDoc, error instanceof Error ? error.message : 'Unknown error');
          result.failedDocuments++;
        }
      }

      console.log(
        `Sync complete: ${result.syncedDocuments} synced, ${result.failedDocuments} failed out of ${result.totalDocuments} total`
      );
    } catch (error) {
      console.error('Error during synchronization', error);
      result.error = error instanceof Error ? error.message : 'Unknown error';
    }

    return result;
  }

  /**
   * Save Race Results locally (to be synced later).
   */
  saveLocal(
    milestoneId: string,
    versionType: string,
    author: string,
    modelData: string
  ): LocalDocument {
    console.log(`Saving Race Results locally for milestone: ${milestoneId}`);

    const localDoc: LocalDocument = {
      localId: '', // Will be generated by storage
      regattaId: this.regattaId,
      timerId: this.timerId,
      milestoneId,
      documentType: 'RACE_RESULTS',
      versionType,
      author,
      description: `Race results for ${milestoneId}`,
      createdAt: new Date().toISOString(),
      modifiedAt: new Date().toISOString(),
      localVersion: 1,
      syncStatus: SyncStatus.PENDING,
      retryCount: 0,
      modelData,
      serializationFormat: 'JSON',
    };

    return this.storage.save(localDoc);
  }

  /**
   * Update Race Results locally.
   */
  updateLocal(localId: string, modelData: string): LocalDocument {
    console.log(`Updating local Race Results: ${localId}`);

    const localDoc = this.storage.findById(localId);
    if (!localDoc) {
      throw new Error(`Document not found: ${localId}`);
    }

    localDoc.modelData = modelData;
    localDoc.modifiedAt = new Date().toISOString();
    localDoc.localVersion += 1;
    localDoc.syncStatus = SyncStatus.PENDING;

    return this.storage.save(localDoc);
  }

  /**
   * Get count of pending documents.
   */
  getPendingCount(): number {
    const pending = this.storage.findPendingSync();
    return pending.filter(
      (doc) =>
        doc.documentType === 'RACE_RESULTS' &&
        doc.timerId === this.timerId
    ).length;
  }

  /**
   * Get all local Race Results for this timer.
   */
  getAllLocal(): LocalDocument[] {
    return this.storage
      .findByRegattaAndType(this.regattaId, 'RACE_RESULTS')
      .filter((doc) => doc.timerId === this.timerId);
  }

  /**
   * Synchronize a single document.
   */
  private async syncDocument(localDoc: LocalDocument): Promise<boolean> {
    // Mark as syncing
    localDoc.syncStatus = SyncStatus.SYNCING;
    this.storage.save(localDoc);

    try {
      if (!localDoc.serverId) {
        // Create new document on server
        return await this.createOnServer(localDoc);
      } else {
        // Update existing document on server
        return await this.updateOnServer(localDoc);
      }
    } catch (error) {
      throw error;
    }
  }

  /**
   * Create a new Race Results document on the server.
   */
  private async createOnServer(localDoc: LocalDocument): Promise<boolean> {
    console.log(`Creating new Race Results on server for milestone: ${localDoc.milestoneId}`);

    const request: DocumentRequest = {
      type: 'RACE_RESULTS',
      regattaId: localDoc.regattaId,
      timerId: localDoc.timerId,
      milestoneId: localDoc.milestoneId,
      versionType: localDoc.versionType,
      author: localDoc.author || 'unknown',
      description: localDoc.description,
      tags: [],
      metadata: {},
      modelData: localDoc.modelData,
    };

    const response = await this.apiClient.createDocument(request);

    // Update local document with server ID and version
    localDoc.serverId = response.documentId;
    localDoc.serverVersion = response.latestVersion;
    localDoc.syncStatus = SyncStatus.SYNCED;
    localDoc.lastSyncedAt = new Date().toISOString();
    localDoc.lastSyncError = undefined;
    localDoc.retryCount = 0;

    this.storage.save(localDoc);

    console.log(
      `Created Race Results on server (server_id: ${response.documentId}, version: ${response.latestVersion})`
    );

    return true;
  }

  /**
   * Update existing Race Results document on the server.
   */
  private async updateOnServer(localDoc: LocalDocument): Promise<boolean> {
    console.log(`Updating Race Results on server (server_id: ${localDoc.serverId})`);

    const changeDescription = `Update from timer ${this.timerId} at ${new Date().toISOString()}`;

    const response = await this.apiClient.updateDocument(
      localDoc.serverId!,
      localDoc.modelData,
      changeDescription
    );

    // Update local document with new server version
    localDoc.serverVersion = response.latestVersion;
    localDoc.syncStatus = SyncStatus.SYNCED;
    localDoc.lastSyncedAt = new Date().toISOString();
    localDoc.lastSyncError = undefined;
    localDoc.retryCount = 0;

    this.storage.save(localDoc);

    console.log(
      `Updated Race Results on server (server_id: ${response.documentId}, new version: ${response.latestVersion})`
    );

    return true;
  }

  /**
   * Mark a document sync as failed.
   */
  private markSyncFailed(localDoc: LocalDocument, error: string): void {
    localDoc.syncStatus = SyncStatus.FAILED;
    localDoc.lastSyncError = error;
    localDoc.retryCount += 1;
    this.storage.save(localDoc);
  }
}
